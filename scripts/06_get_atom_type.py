from collections import defaultdict
from pathlib import Path

PROVENANCE_FILE = "ep2_parameter_provenance.tsv"


def append_provenance(section, key, atom_ids, value_1, value_2, source, source_file, notes=""):
    """Append one machine-readable provenance record."""
    path = Path(PROVENANCE_FILE)
    write_header = not path.exists()
    with path.open("a") as handle:
        if write_header:
            handle.write("section\tatom_type_key\tatom_ids\tvalue_1\tvalue_2\tsource\tsource_file\tnotes\n")
        handle.write(
            f"{section}\t{key}\t{atom_ids}\t{value_1}\t{value_2}\t"
            f"{source}\t{source_file}\t{notes}\n"
        )


def make_comment(source, source_file, atom_ids, extra=""):
    extra_text = f" {extra}" if extra else ""
    return f"# ep2_source={source} source_file={source_file} atoms={atom_ids}{extra_text}"


# Extract atom types from a MOL2 file.
def extract_atom_types_from_mol2(file_path):
    with open(file_path, 'r') as file:
        lines = file.readlines()

    atom_types = {}
    is_atom_section = False

    for line in lines:
        if line.startswith("@<TRIPOS>ATOM"):
            is_atom_section = True
            continue
        if line.startswith("@<TRIPOS>BOND"):
            is_atom_section = False
            break
        if is_atom_section:
            parts = line.split()
            if len(parts) >= 6:
                atom_id = int(parts[0])
                atom_type = parts[5]
                atom_types[atom_id] = atom_type

    return atom_types


# Process bond, angle, and dihedral information from an input file and write to an output file.
def process_bond_angle_dihedral_file(atom_types, input_file, output_file):
    source_file = input_file

    with open(input_file, 'r') as infile, open(output_file, 'w') as outfile:
        section = None

        # Write header
        outfile.write("Remark line goes here THIS FILE IS GENERATED BY easyPARM\n")
        outfile.write("Remark ep2: parameter provenance comments use machine-readable ep2_source tags\n")
        outfile.write("MASS\n")

        for line in infile:
            line = line.strip()

            # Determine the current section (BOND, ANGLE, or DIHE)
            if line.startswith("Bond Information:"):
                section = "BOND"
                outfile.write("\n")
                outfile.write("BOND\n")
                continue
            elif line.startswith("Angle Information:"):
                section = "ANGLE"
                outfile.write("\n")
                outfile.write("ANGLE\n")
                continue
            elif line.startswith("Dihedral Information:"):
                section = "DIHE"
                outfile.write("\n")
                outfile.write("DIHE\n")
                continue

            parts = line.split()

            # Process BOND information.
            if section == "BOND" and len(parts) == 4:
                atom1_id, atom2_id = int(parts[0]), int(parts[1])
                distance, force = parts[2], parts[3]
                atom1_type = atom_types.get(atom1_id, "Unknown")
                atom2_type = atom_types.get(atom2_id, "Unknown")
                key = f"{atom1_type}-{atom2_type}"
                atom_ids = f"{atom1_id},{atom2_id}"
                comment = make_comment("HESSIAN_RAW", source_file, atom_ids)
                outfile.write(f"{key}    {force}    {distance}    {comment}\n")
                append_provenance("BOND", key, atom_ids, force, distance, "HESSIAN_RAW", source_file)

            # Process ANGLE information.
            elif section == "ANGLE" and len(parts) == 5:
                atom1_id, atom2_id, atom3_id = int(parts[0]), int(parts[1]), int(parts[2])
                angle, force = parts[3], parts[4]
                atom1_type = atom_types.get(atom1_id, "Unknown")
                atom2_type = atom_types.get(atom2_id, "Unknown")
                atom3_type = atom_types.get(atom3_id, "Unknown")
                key = f"{atom1_type}-{atom2_type}-{atom3_type}"
                atom_ids = f"{atom1_id},{atom2_id},{atom3_id}"
                comment = make_comment("HESSIAN_RAW", source_file, atom_ids)
                outfile.write(f"{key}     {force}     {angle}     {comment}\n")
                append_provenance("ANGLE", key, atom_ids, force, angle, "HESSIAN_RAW", source_file)

            # Process DIHE information.
            # Important: this line does not derive a torsional barrier from the Hessian.
            # The atom sequence comes from the input geometry/topology, but the torsional
            # parameters below are generic placeholders.
            elif section == "DIHE" and len(parts) == 5:
                atom1_id, atom2_id, atom3_id, atom4_id = int(parts[0]), int(parts[1]), int(parts[2]), int(parts[3])
                atom1_type = atom_types.get(atom1_id, "Unknown")
                atom2_type = atom_types.get(atom2_id, "Unknown")
                atom3_type = atom_types.get(atom3_id, "Unknown")
                atom4_type = atom_types.get(atom4_id, "Unknown")
                key = f"{atom1_type}-{atom2_type}-{atom3_type}-{atom4_type}"
                atom_ids = f"{atom1_id},{atom2_id},{atom3_id},{atom4_id}"
                comment = make_comment(
                    "GENERIC_DIHEDRAL_PLACEHOLDER",
                    source_file,
                    atom_ids,
                    "geometry_from_input=yes barrier_from_hessian=no"
                )
                outfile.write(f"{key}   3    0.000       0.0000           3.000   {comment}\n")
                append_provenance(
                    "DIHE",
                    key,
                    atom_ids,
                    "3;0.000;0.0000;3.000",
                    "",
                    "GENERIC_DIHEDRAL_PLACEHOLDER",
                    source_file,
                    "geometry_from_input=yes; barrier_from_hessian=no",
                )

        # Write footer
        outfile.write("\n")
        outfile.write("IMPROPER\n")
        outfile.write("\n")
        outfile.write("NONBON\n")
        outfile.write("\n")


# Inputs
mol2_file_path = 'NEW_COMPLEX.mol2'
input_file_path = 'bond_angle_dihedral_data.dat'
# Output
output_file_path = 'forcefield.dat'

# Extract atom types from the MOL2 file
atom_types = extract_atom_types_from_mol2(mol2_file_path)

# Process the bond, angle, and dihedral file and save the results
process_bond_angle_dihedral_file(atom_types, input_file_path, output_file_path)
